"""Widget confirm card (desktop + phone), XSS in answers, kiosk, badge."""
from ui import *
import hlm, json, time
api = hlm.Client(); api.login()
api.call("PUT", "/api/agent/policy/hosts/lab1", {"mode": "active"})
api.call("PUT", "/api/agent/policy/hosts/lab1/actions/container.restart", {"rule": "ask"})
R = lambda n: hlm.stub([{"tool_calls": [{"name": "container__restart", "arguments": {"host": "lab1", "name": n, "reason": "ui widget"}}]}, {"text": "Widget restart finished."}])
with sync_playwright() as p:
    b = browser(p)
    # 1 desktop widget approve
    pg = page(b, 1440, 900, url="/#containers")
    pg.wait_for_selector(".ag-fab:not([hidden])", timeout=15000)
    shot(pg, "f1-containers-fab")
    pg.click(".ag-fab")
    pg.wait_for_selector("#agw-ta")
    shot(pg, "f1-widget-open")
    before = hlm.started("hlm-target1", "worker")
    pg.fill("#agw-ta", R("worker"))
    pg.click("#agw-send")
    pg.wait_for_selector("#agw-msgs .ag-confirm [data-ap]", timeout=30000)
    shot(pg, "f1-widget-card")
    print("card text:", pg.inner_text("#agw-msgs .ag-confirm")[:300].replace("\n", " | "))
    # badge
    print("badge:", pg.evaluate("() => [...document.querySelectorAll('.ag-badge')].map(e=>[e.innerText, !!e.offsetParent])"))
    pg.locator("#agw-msgs .ag-confirm [data-ap]").click()
    pg.wait_for_function("() => document.querySelector('#agw-msgs').innerText.includes('Widget restart finished.')", timeout=30000)
    time.sleep(1)
    print("desktop widget approve restarted:", before != hlm.started("hlm-target1", "worker"))
    shot(pg, "f1-widget-done")
    # XSS
    xss = hlm.stub([{"text": "<img src=x onerror=\"window.__x=1\"> **bold** [click](javascript:window.__y=1) [ok](#containers?host=lab1) <script>window.__z=1</script> \" onmouseover=\"window.__w=1"}])
    pg.fill("#agw-ta", xss); pg.click("#agw-send")
    pg.wait_for_timeout(4000)
    links = pg.evaluate("() => [...document.querySelectorAll('#agw-msgs a')].map(a=>a.getAttribute('href'))")
    imgs = pg.evaluate("() => document.querySelectorAll('#agw-msgs img').length")
    print("XSS: flags", pg.evaluate("() => [window.__x, window.__y, window.__z, window.__w]"), "links", links, "imgs", imgs)
    for a in pg.locator("#agw-msgs a").all():
        try: a.click(timeout=1000)
        except Exception: pass
    print("XSS after clicks:", pg.evaluate("() => [window.__x, window.__y]"), "url:", pg.url)
    shot(pg, "f1-widget-xss")
    pg.context.close()
    # 2 phone widget reject
    pg = page(b, 390, 844, url="/#overview")
    pg.wait_for_selector(".ag-fab:not([hidden])", timeout=15000)
    shot(pg, "f2-phone-overview-fab")
    pg.click(".ag-fab")
    before = hlm.started("hlm-target1", "worker")
    pg.fill("#agw-ta", R("worker")); pg.click("#agw-send")
    pg.wait_for_selector("#agw-msgs .ag-confirm", timeout=30000)
    shot(pg, "f2-phone-widget-card")
    btns = pg.evaluate("() => [...document.querySelectorAll('#agw-msgs .ag-confirm button')].map(b=>[b.innerText, JSON.stringify(b.getBoundingClientRect())])")
    print("phone card buttons:", btns)
    rej = pg.locator("#agw-msgs .ag-confirm button", has_text="Reject")
    rej.first.click()
    pg.wait_for_timeout(3000)
    shot(pg, "f2-phone-widget-rejected")
    print("phone reject restarted:", before != hlm.started("hlm-target1", "worker"))
    print("widget controls:", pg.evaluate("() => [...document.querySelectorAll('.ag-panel button, .ag-panel a')].filter(e=>e.offsetParent).map(e=>(e.innerText||e.title||e.getAttribute('aria-label')||'').trim())"))
    pg.context.close()
    # 3 kiosk
    pg = page(b, 1440, 900, url="/?display=1")
    pg.wait_for_timeout(3000)
    print("kiosk fab display:", pg.evaluate("() => { const f = document.querySelector('.ag-fab'); return f ? [getComputedStyle(f).display, f.hidden, !!f.offsetParent] : 'none'; }"))
    shot(pg, "f3-kiosk")
    pg.context.close()
    dump_errors()
