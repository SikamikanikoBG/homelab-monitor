from ui import *
with sync_playwright() as p:
    b = browser(p)
    pg = page(b, 1440, 900)
    agent(pg, "activity")
    rows = lambda: pg.locator("tr[data-run]").count()
    pg.wait_for_timeout(5000); print("rows:", rows())
    sels = pg.locator("#ag-cockpit select")
    print("selects:", [sels.nth(i).evaluate("s=>[...s.options].map(o=>o.text).slice(0,5)") for i in range(sels.count())])
    act = [i for i in range(sels.count()) if "All actions" in sels.nth(i).inner_text()][0]
    sels.nth(act).select_option(label=[o for o in sels.nth(act).evaluate("s=>[...s.options].map(o=>o.text)") if "Stop a container" in o][0]); pg.wait_for_timeout(1500)
    print("action=stop rows:", rows(), pg.evaluate("() => [...document.querySelectorAll('tr[data-run]')].slice(0,4).map(r=>r.innerText.slice(0,80))"))
    sels.nth(act).select_option(index=0); pg.wait_for_timeout(1000)
    pg.fill("#ag-cockpit input[placeholder*='Search']", "RunNow"); pg.keyboard.press("Enter"); pg.wait_for_timeout(1500)
    print("search RunNow rows:", rows())
    pg.fill("#ag-cockpit input[placeholder*='Search']", ""); pg.keyboard.press("Enter"); pg.wait_for_timeout(1000)
    pg.fill("#ag-cockpit input[type=date]", "2026-10-23"); pg.wait_for_timeout(1500)
    print("date 2026-10-23 rows:", rows())
    pg.fill("#ag-cockpit input[type=date]", ""); pg.wait_for_timeout(1500)
    print("rows reset:", rows())
    more = pg.locator("#ag-cockpit button", has_text="more")
    print("load more buttons:", more.count())
    if more.count():
        more.first.click(); pg.wait_for_timeout(1500); print("rows after more:", rows())
    pg.context.close()
    pg = page(b, 390, 844, dark=True)
    agent(pg, "activity")
    pg.locator("tr[data-run]").nth(3).click(); pg.wait_for_timeout(1500)
    shot(pg, "p2-phone-activity-tap")
    print("phone detail top:", pg.evaluate("document.querySelector('#ag-rundetail').getBoundingClientRect().top"), "viewport h 844")
    dump_errors()
